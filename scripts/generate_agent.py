"""Generate the project's QA agent skill from runner/ (self-contained: SKILL.md + scripts + references).

Usage: python generate_agent.py --name qa-agent-myproject [--project "My Project"] [--root .] [--out DIR] [--force]
  --name     skill folder and slash command; default qa-agent-<project-slug>
  --project  display name; default config project.name, else the root folder name
  --root     project root (the folder holding .qa/); default: found from the cwd upward, else cwd
  --out      output folder; default <root>/.claude/skills/<name>
  --force    overwrite a folder this script did not create
Re-run any time to update the agent after the config or the setup skill changes. Safe: only the
generated folder is touched, never .qa/ (except project.agent_name in the config).
"""
from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
SETUP = HERE.parent
RUNNER = SETUP / "runner"
MARKER = ".generated-by-qa-agent-setup"
NAME_RE = re.compile(r"^[a-z][a-z0-9-]{2,47}$")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "project"


def find_root(start: pathlib.Path) -> pathlib.Path:
    for folder in [start, *start.parents]:
        if (folder / ".qa" / "qa.config.yaml").is_file():
            return folder
    return start


def config_project_name(root: pathlib.Path) -> str:
    cfg = root / ".qa" / "qa.config.yaml"
    if cfg.is_file():
        m = re.search(r"^project:\s*\n(?:[ \t]+.*\n)*?[ \t]+name:\s*[\"']?([^\"'#\n]+)", cfg.read_text(), re.M)
        if m and "<" not in m.group(1):
            return m.group(1).strip()
    return root.name


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name")
    ap.add_argument("--project")
    ap.add_argument("--root")
    ap.add_argument("--out")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()

    root = pathlib.Path(a.root).resolve() if a.root else find_root(pathlib.Path.cwd().resolve())
    project = a.project or config_project_name(root)
    name = a.name or f"qa-agent-{slug(project)}"
    if not NAME_RE.match(name):
        sys.exit(f"bad name '{name}': lowercase letters, digits, dashes; 3-48 chars; start with a letter")
    if name in ("qa-agent-setup", "qa-agent"):
        sys.exit(f"'{name}' is reserved: pick a project-specific name, e.g. qa-agent-{slug(project)}")

    out = pathlib.Path(a.out).resolve() if a.out else root / ".claude" / "skills" / name
    if out.exists():
        if not (out / MARKER).exists() and not a.force:
            sys.exit(f"{out} exists and was not generated by this script: use --force or another --name/--out")
        shutil.rmtree(out)
    out.mkdir(parents=True)

    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store")
    shutil.copytree(RUNNER / "scripts", out / "scripts", ignore=ignore)
    shutil.copytree(RUNNER / "references", out / "references", ignore=ignore)
    for script in ("verify_setup.py", "qa_config_set.py"):
        shutil.copy2(HERE / script, out / "scripts" / script)
    shutil.copy2(SETUP / "references" / "repair.md", out / "references" / "repair.md")
    for sh in (out / "scripts" / "frontend").glob("*.sh"):
        sh.chmod(0o755)

    try:
        skill_dir = out.relative_to(root).as_posix()
    except ValueError:
        skill_dir = str(out)
    text = (RUNNER / "SKILL.md.tmpl").read_text()
    for key, val in {"NAME": name, "PROJECT": project, "SKILL_DIR": skill_dir}.items():
        text = text.replace("{{" + key + "}}", val)
    (out / "SKILL.md").write_text(text)
    (out / MARKER).write_text("Regenerate with qa-agent-setup/scripts/generate_agent.py; manual edits are overwritten.\n")

    cfg = root / ".qa" / "qa.config.yaml"
    if cfg.is_file():
        subprocess.run([sys.executable, str(out / "scripts" / "qa_config_set.py"), "project.agent_name", name,
                        "--config", str(cfg)], capture_output=True, text=True)
    print(f"generated {name} -> {out}")
    print(f"run it with: /{name} <task>   (commit {skill_dir}/ so teammates get it)")


if __name__ == "__main__":
    main()
